package ru.taskflow.assistant.api;

/**
 * Закрытый список причин отказа от действия (no_action) — не свободный
 * текст: превращает провалы категории NEGATIVE в измеримые доли.
 */
public enum DeclineReason {
    /** Пользователь спрашивает, а не поручает — «покажи задачи на завтра». */
    QUESTION,
    /** Реплика без задачи — «спасибо», «привет». */
    CHITCHAT,
    /** Команда не восстанавливается, нужна переформулировка. */
    UNCLEAR,
    /** Просьба напомнить о моменте, который уже прошёл. */
    PAST
}
