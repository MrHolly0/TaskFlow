package ru.taskflow.user.application;

/**
 * Доставка кода входа звонком на телефон. Отдельный интерфейс, а не прямая
 * зависимость от Ucaller — так уже было с LlmProvider для Groq, и в тот раз
 * смена модели поставщика без абстракции стоила времени; здесь та же
 * предосторожность на случай смены поставщика звонков.
 */
public interface PhoneVerificationProvider {

    boolean isAvailable();

    /**
     * Инициирует звонок с переданным кодом и возвращает код, который
     * провайдер фактически использует — не обязательно тот же самый.
     * У звонкового подтверждения код передаётся последними цифрами номера
     * звонящего, а пул таких номеров у провайдера конечен: даже если он
     * обязан использовать наш code по документации, доверять стоит только
     * ответу. Вызывающая сторона обязана сохранять именно возвращённое
     * значение, а не то, что передала на вход.
     */
    String sendCode(String phoneE164, String code);
}
