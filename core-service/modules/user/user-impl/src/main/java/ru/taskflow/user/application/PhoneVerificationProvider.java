package ru.taskflow.user.application;

/**
 * Доставка кода входа звонком на телефон. Отдельный интерфейс, а не прямая
 * зависимость от Ucaller — так уже было с LlmProvider для Groq, и в тот раз
 * смена модели поставщика без абстракции стоила времени; здесь та же
 * предосторожность на случай смены поставщика звонков.
 */
public interface PhoneVerificationProvider {

    boolean isAvailable();

    /**
     * Просит провайдера ждать входящий звонок с этого номера и возвращает
     * номер, на который нужно позвонить, плюс идентификатор обращения у
     * провайдера. Основной способ подтверждения: исходящий вызов человеку
     * (см. {@link #sendCode}) на реальном номере не доходил при подтверждённой
     * доставке у Ucaller — звонок в обратную сторону снимает проблему тем,
     * что заблокировать исходящий вызов человека некому.
     */
    PhoneConfirmationRequest requestConfirmation(String phoneE164);

    /**
     * Инициирует исходящий звонок с переданным кодом и возвращает код,
     * который провайдер фактически использует — не обязательно тот же самый.
     * Оставлен нетронутым и неиспользуемым контроллерами: доставка исходящих
     * звонков на реальный номер владельца не сработала (см. историю чата),
     * хотя Ucaller каждый раз отчитывался об успехе. Если Ucaller подтвердит
     * и починит доставку, этот способ снова станет пригоден — тогда его нужно
     * будет заново подключить и вернуть экран ввода кода на фронтенде.
     */
    String sendCode(String phoneE164, String code);
}
