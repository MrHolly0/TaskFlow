package ru.taskflow.task.api;

/**
 * Откуда взялась задача — вручную или через ассистента, и по какому каналу.
 *
 * {@link #WEB}, {@link #BOT_TEXT} и {@link #BOT_VOICE} — исторические значения:
 * до этого перечисления ими помечались и подтверждённые пользователем действия
 * ассистента, и деградация (реплика не разобралась, задача создана без
 * подтверждения) — по каналу отличить получалось, а подтверждено или
 * деградировано — нет. Новый код их не пишет, но старые строки в базе не
 * трогаем и не перетолковываем: различить задним числом, каким из двух путей
 * создана конкретная старая задача, нельзя.
 */
public enum TaskSource {
    /** Заведена вручную — форма или API, без участия ассистента. */
    MANUAL,

    /** @deprecated исторически: подтверждённое веб-действие или веб-деградация, неразличимо. */
    @Deprecated WEB,
    /** @deprecated исторически: подтверждённое текстовое действие в Telegram или деградация, неразличимо. */
    @Deprecated BOT_TEXT,
    /** @deprecated исторически: подтверждённое голосовое действие в Telegram или деградация, неразличимо. */
    @Deprecated BOT_VOICE,

    /** Пользователь подтвердил предложение ассистента в веб-чате. */
    ASSISTANT_WEB,
    /** Пользователь подтвердил предложение ассистента по тексту в Telegram. */
    ASSISTANT_BOT_TEXT,
    /** Пользователь подтвердил предложение ассистента по голосовому в Telegram. */
    ASSISTANT_BOT_VOICE,

    /** Реплика из веб-чата не разобралась — задача создана автоматически, без подтверждения. */
    ASSISTANT_WEB_DEGRADED,
    /** Текстовая реплика в Telegram не разобралась — задача создана автоматически, без подтверждения. */
    ASSISTANT_BOT_TEXT_DEGRADED,
    /** Голосовая реплика в Telegram не распозналась или не разобралась — задача создана автоматически, без подтверждения. */
    ASSISTANT_BOT_VOICE_DEGRADED,

    /**
     * Следующее вхождение повторяющейся задачи, созданное при закрытии
     * предыдущего (см. блок А в дорожной карте про recurrences) — не ввод
     * пользователя и не действие ассистента, поэтому не наследует source
     * закрытой задачи.
     */
    RECURRENCE
}
