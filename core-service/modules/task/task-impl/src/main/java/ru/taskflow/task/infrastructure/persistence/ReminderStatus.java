package ru.taskflow.task.infrastructure.persistence;

/**
 * PENDING — ещё должно сработать. CANCELLED — задача завершена, отменена или
 * получила новый срок раньше, чем напоминание успело сработать (см.
 * TaskReminderService.cancelForTask).
 * <p>
 * Настойчивость по конкретному напоминанию (отложить/снять именно его, не
 * трогая остальные напоминания той же задачи) — за пределами этого прохода:
 * состояния SNOOZED/DISMISSED сюда сознательно не добавлены, пока для них
 * нет ни одного вызывающего места — тот же класс дефектов, что и в А5.
 */
public enum ReminderStatus {
    PENDING, CANCELLED
}
